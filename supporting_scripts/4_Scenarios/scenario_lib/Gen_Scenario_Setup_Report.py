def _scenario_map_payload(model_config: Dict[str, Any], unit_ids: List[str],
                          max_points: int = 120000) -> Optional[Dict[str, Any]]:
    """Geometry of the model's spatial units (HRUs / sub-basins / reaches) for
    the Scenarios-tab map, as a compact WGS84 GeoJSON whose features carry
    only ``{"id": <unit id>}``.

    The interactive layer is the shapefile (basin polygons, else the river
    network) whose attribute values match the run's unit ids best — the id
    column is detected from the data, so it works whatever the mapping key is
    called. The other shapefile, if any, is drawn as a non-interactive
    backdrop. Returns ``None`` when no geometry can be loaded (missing file,
    fiona / shapely not installed): the tab then works with typed unit ids."""
    try:
        from calibration_lib.Gen_Calibration_Results_Report import _load_shapefile_as_geojson
    except ImportError:                                  # pragma: no cover
        from Gen_Calibration_Results_Report import _load_shapefile_as_geojson
    man = model_config.get("_baseline_manifest") or {}
    bas = model_config.get("ss_method_copernicus_basins_hrus") or {}
    bas = bas if isinstance(bas, dict) else {}
    # candidates: the model config's OWN shapefiles first, then the baseline
    # manifest's (a manifest found next to the executable can belong to
    # another case — the unit-id match below decides, not the order)
    cands, _seen = [], set()
    for src, path in (("config", bas.get("path_to_shp")), ("config", model_config.get("river_network_shapefile")),
                      ("manifest", man.get("basin_shapefile")), ("manifest", man.get("river_network_shapefile"))):
        if path and str(path) not in _seen and os.path.isfile(str(path)):
            _seen.add(str(path))
            cands.append((src, str(path)))
    pref = [k for k in (man.get("basin_mapping_key"), bas.get("mapping_key"),
                        man.get("user_openwq_h5_mapping_key"), man.get("h5_mapping_key"),
                        man.get("river_network_mapping_key"),
                        model_config.get("river_network_mapping_key")) if k]
    want = {_scn._norm_id(u) for u in (unit_ids or [])}
    layers = []
    for _order, (src, path) in enumerate(cands):
        try:
            gj, _b = _load_shapefile_as_geojson(str(path))
        except Exception as e:
            logger.info(f"scenario map: could not read {path}: {e}")
            continue
        feats = (gj or {}).get("features") or []
        if not feats:
            continue
        props0 = feats[0].get("properties") or {}
        cols = [k for k in pref if k in props0] + [k for k in props0 if k not in pref]
        best_key, best_n = None, -1
        for k in cols:
            vals = [_scn._norm_id((f.get("properties") or {}).get(k)) for f in feats]
            if want:
                n = len(set(vals) & want)
            else:     # no unit list known: a preferred key, else a unique-valued column
                n = len(feats) + 1 if k in pref else (len(feats) if len(set(vals)) == len(feats) else 0)
            if n > best_n:
                best_key, best_n = k, n
        gtype = str((feats[0].get("geometry") or {}).get("type") or "")
        layers.append({"path": str(path), "feats": feats, "key": best_key, "n": max(best_n, 0),
                       "kind": "polygon" if "Polygon" in gtype else "line", "src": src, "order": _order})
    if not layers:
        return None
    layers.sort(key=lambda d: (-d["n"], 0 if d["kind"] == "polygon" else 1, d["order"]))
    main = layers[0]
    # backdrop: the other shapefile of the SAME source (never another case's)
    ctx = next((d for d in layers[1:] if d["src"] == main["src"] and d["kind"] != main["kind"]), None)
    if want and main["n"] == 0:
        logger.info("scenario map: no shapefile attribute matches the run's unit ids — map skipped")
        return None

    def _npts(c):
        if not isinstance(c, (list, tuple)) or not c:
            return 0
        return 1 if isinstance(c[0], (int, float)) else sum(_npts(x) for x in c)

    def _round(c):
        if isinstance(c, (list, tuple)):
            if c and isinstance(c[0], (int, float)):
                return [round(float(c[0]), 5), round(float(c[1]), 5)]
            return [_round(x) for x in c]
        return c

    def _compact(feats, key, budget):
        geoms = [f.get("geometry") for f in feats]
        total = sum(_npts((g or {}).get("coordinates")) for g in geoms)
        if total > budget:
            try:
                from shapely.geometry import shape, mapping
                shp = [shape(g) if g else None for g in geoms]
                xs = [s.bounds for s in shp if s is not None and not s.is_empty]
                ext = max(max(b[2] for b in xs) - min(b[0] for b in xs),
                          max(b[3] for b in xs) - min(b[1] for b in xs)) if xs else 1.0
                tol = ext * 2e-4
                for _ in range(8):
                    simp = [s.simplify(tol, preserve_topology=True) if s is not None else None for s in shp]
                    geoms = [mapping(s) if s is not None else None for s in simp]
                    total = sum(_npts((g or {}).get("coordinates")) for g in geoms)
                    if total <= budget:
                        break
                    tol *= 2.0
            except Exception as e:
                logger.info(f"scenario map: geometry not simplified ({e})")
        out = []
        for f, g in zip(feats, geoms):
            if not g:
                continue
            props = {"id": _scn._norm_id((f.get("properties") or {}).get(key))} if key else {}
            out.append({"type": "Feature", "properties": props,
                        "geometry": {"type": g.get("type"), "coordinates": _round(g.get("coordinates"))}})
        return {"type": "FeatureCollection", "features": out}

    gj_main = _compact(main["feats"], main["key"], max_points)
    ids, seen = [], set()
    for f in gj_main["features"]:
        i = f["properties"].get("id")
        if i and i not in seen:
            seen.add(i)
            ids.append(i)

    def _k(x):
        try:
            return (0, float(x), "")
        except (TypeError, ValueError):
            return (1, 0.0, str(x))
    ids.sort(key=_k)
    host = str(model_config.get("hostmodel") or "").lower()
    label = "HRU" if host == "summa" else ("sub-basin" if main["kind"] == "polygon" else "reach")
    return {"geojson": gj_main,
            "context": _compact(ctx["feats"], None, max_points // 3) if ctx else None,
            "geom": main["kind"], "label": label, "key": main["key"], "ids": ids,
            "n_matched": main["n"], "n_features": len(gj_main["features"]),
            "source": os.path.basename(main["path"])}


