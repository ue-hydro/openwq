def _caller_template_stem(default="scenarios"):
    """Basename (no extension) of the *scenario template* that called into
    this module — used to name the report and the generated run script.

    Walks the stack outward and returns the first frame whose file lives
    OUTSIDE ``scenario_lib`` *and* ``calibration_lib`` (i.e. the user's
    ``scenario_config_template*.py``).  Falls back to ``default``."""
    try:
        _here = os.path.dirname(os.path.abspath(__file__))
        for fr in inspect.stack()[1:]:
            fn = fr.filename or ""
            if not fn or fn.startswith("<"):
                continue
            d = os.path.dirname(os.path.abspath(fn))
            if d == _here or os.path.basename(d) in ("scenario_lib", "calibration_lib"):
                continue
            stem = os.path.splitext(os.path.basename(fn))[0]
            if stem:
                return stem
    except Exception:
        pass
    return default


def generate_interactive_scenario_setup(*, output_dir: str, model_config: Dict[str, Any],
                                        config_run_path: str,
                                        hpc_settings_path: Optional[str] = None,
                                        template_path: Optional[str] = None) -> Optional[str]:
    """Write ``<stem>_scenario_config_report.html`` into ``output_dir``.

    ``stem`` is the basename of the scenario template: ``template_path`` when
    the template passes its own ``__file__`` (preferred), otherwise detected
    from the call stack."""
    try:
        os.makedirs(output_dir, exist_ok=True)
        config_run_path = _true_case_path(os.path.abspath(config_run_path))
        stem = (os.path.splitext(os.path.basename(template_path))[0] if template_path
                else _caller_template_stem(default="scenarios"))
        report_path = os.path.join(output_dir, f"{stem}_scenario_config_report.html")
        base_dir = str(model_config.get("dir2save_input_files") or "")
        prov = _ccfg.read_calibrated_setup(base_dir) or {}
        container_config = _ci.get_container_config(model_config) or {}
        rt_default = _runtime_default_for_this_machine(container_config.get("container_runtime", "docker"))
        hpc = _load_hpc_settings(hpc_settings_path) if hpc_settings_path else {}
        species = _scn.resolve_model_species(model_config)

        # BGC parameter locations (for the in-stream lever): from the BGC template
        param_info: Dict[str, Any] = {}
        try:
            try:
                from calibration_lib import extract_parameters as _ep
            except ImportError:                      # pragma: no cover
                import extract_parameters as _ep
            bgc_tpl = _ci.get_bgc_template_path(model_config)
            if bgc_tpl:
                for p in _ep.extract_calibration_parameters(bgc_tpl):
                    if p.get("name") and p.get("path"):
                        param_info[p["name"]] = {"path": p["path"], "module": "bgc"}
        except Exception as _e:
            logger.info(f"BGC parameter list not built for the in-stream lever: {_e}")
        scn_info = _scn.scenario_info_for_report(model_config, str(output_dir), param_info)
        # geometry of the spatial units for the "where" map (None -> typed ids only)
        try:
            map_payload = _scenario_map_payload(model_config, scn_info.get("units") or [])
        except Exception as _e:
            logger.info(f"scenario map not built: {_e}")
            map_payload = None

        # model period (defaults of the scored period)
        sim = None
        try:
            sim = _ci.get_model_sim_period(model_config)
        except Exception:
            sim = None
        _p0 = (sim or {}).get("sim_start") if isinstance(sim, dict) else None
        _p1 = (sim or {}).get("sim_end") if isinstance(sim, dict) else None
        default_period = (str(_p0), str(_p1)) if _p0 and _p1 else None

        _scn_lib_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # supporting_scripts/4_Scenarios
        work_dir = os.path.abspath(output_dir)
        script_name = f"{stem}_scenarios_run.py"
        save_hint = os.path.join(work_dir, script_name)
        results_path = os.path.join(work_dir, f"{stem}_scenarios_report.html")

        H: List[str] = []
        H.append(rh.build_html_head("OpenWQ Scenario Analysis — Interactive Setup",
                                    extra_css=rh.get_interactive_layout_css()))
        H.append("<body>")
        H.append('<div class="split-layout">')
        H.append('<div class="top-bar">')
        H.append(rh.build_compact_header(
            title='Open<span style="color:var(--secondary);">WQ</span> &mdash; Interactive Scenario Setup',
            badge_text="SCENARIOS", badge_class="badge-accent"))
        H.append('</div>')
        H.append('<div class="panes-row">')
        H.append('<div class="config-pane" id="configPane">')
        H.append("""
<div class="tab-bar">
    <button class="tab-btn active" data-tab="overview" onclick="switchTab('overview')">Overview</button>
    <button class="tab-btn" data-tab="scenarios" onclick="switchTab('scenarios')">Scenarios</button>
</div>""")
        H.append('<div class="tab-panel active" data-tab="overview">')
        H.append(_build_overview_section(model_config, config_run_path, base_dir, prov, species,
                                         sim if isinstance(sim, dict) else None, scn_info))
        H.append('</div>')
        H.append('<div class="tab-panel" data-tab="scenarios">')
        H.append(_build_interactive_scenarios_section(scn_info, default_period, None, species,
                                                      runtime_default=rt_default, hpc=hpc,
                                                      map_payload=map_payload))
        H.append('</div>')
        H.append('</div>')   # config-pane
        H.append('<div class="pane-resizer" id="paneResizer"></div>')
        H.append(_build_script_pane(work_dir, script_name, save_hint, results_path, container_config))
        H.append('</div>')   # panes-row
        H.append('</div>')   # split-layout
        H.append(_build_js(config_run_path, work_dir, stem, _scn_lib_dir, scn_info, map_payload))
        H.append("</body></html>")
        with open(report_path, "w", encoding="utf-8") as f:
            f.write("\n".join(H))
        logger.info(f"Interactive scenario setup report saved to: {report_path}")
        return report_path
    except Exception as e:
        logger.error(f"Failed to generate the scenario setup report: {e}", exc_info=True)
        return None


