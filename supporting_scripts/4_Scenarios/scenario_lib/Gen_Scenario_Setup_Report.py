    _dc = (container_config or {}).get("docker_compose_path", "")
    containers_dir = os.path.dirname(_dc) if _dc else os.path.normpath(os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "..", "..", "containers"))
    wake = "caffeinate -i -s " if os_name == "Darwin" else (
        'systemd-inhibit --what=idle:sleep --why="OpenWQ scenarios" ' if os_name == "Linux" else "")
    if os_name == "Windows":
        docker_cmd = f'cd /d "{containers_dir}" && docker compose up -d'
        run_cmd = f'cd /d "{work_dir}" && python "{script_name}"'
        rep_cmd = f'cd /d "{work_dir}" && python "{script_name}" --report'
        open_cmd = "start"
